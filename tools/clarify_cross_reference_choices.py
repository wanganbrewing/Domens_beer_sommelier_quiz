def main() -> None:
    data = json.loads(DATA_PATH.read_text(encoding="utf-8"))
    questions = {question["id"]: question for question in data["questions"]}

    for question_id, (old_choice, new_choice, new_reason) in REPLACEMENTS.items():
        question = questions[question_id]
        matches = [index for index, choice in enumerate(question["choices"]) if choice == old_choice]
        if len(matches) != 1:
            raise ValueError(f"{question_id}: expected one {old_choice!r}, got {matches}")
        index = matches[0]
        question["choices"][index] = new_choice
        question["explanation"] = question["explanation"].replace(old_choice, new_choice)
        question["choiceReasons"] = [
            reason.replace(old_choice, new_choice) for reason in question["choiceReasons"]
        ]
        question["choiceReasons"][index] = new_reason

    data["metadata"]["version"] += "-self-contained-choices"
    DATA_PATH.write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"Updated {len(REPLACEMENTS)} cross-referencing choices.")


if __name__ == "__main__":
    main()
